const conteudo = document.querySelector(".conteudo");

function mostrarFilmes(lista){

    //limpa a tela
    conteudo.innerHTML = "";

    //Para cada filme da lista, execute este bloco de código.
    lista.forEach(filme=>{

        //pega o que já existe e acrescenta no final
        conteudo.innerHTML += `

        <article class="itens">

            <h2 class="titulo">

                ${filme.titulo}

            </h2>

            <ul class="categorias">

                ${filme.categorias.map(categoria=>`<li>${categoria}</li>`).join("")}

            </ul>

            <div class="conteudo-card">

                <div class="ladoEsquerdo">

                    <img src="${filme.imagem}">

                </div>

                <div class="ladoDireito">

                    <h3>

                        Diretor:

                        <a href="#">

                            ${filme.diretor}

                        </a>

                    </h3>

                    <hr>

                    <h3>

                        Atores:
                        
                         ${filme.atores.map(ator=>`<a href="#">${ator}</a>`).join("")}

                    </h3>

                    <hr>

                    <h4>Sinopse</h4>

                    <p class="sinopse">

                        ${filme.sinopse}

                    </p>
                 
                </div>

            </div>

        </article>

        `;

    });

}

mostrarFilmes(filmes);

const input = document.getElementById("search");

input.addEventListener("input", ()=>{

    const texto = input.value.toLowerCase();

    const resultado = filmes.filter(filme=>{

        return filme.titulo.toLowerCase().includes(texto);

    });

    mostrarFilmes(resultado);

});
